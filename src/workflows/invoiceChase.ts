import { DAYS, defineWorkflow, GMAIL_RETRY, ref } from "./build";

export const INVOICE_CHASE_ID = "def_ironspark_invoice_chase";

const note = (id: string, summary: string, label = "Stop - it is paid") => ({
  id,
  type: "ACTION" as const,
  stepKey: "addTimelineNote",
  label,
  config: { params: { clientId: ref("load_invoice.clientId"), summary, workflow: "Invoice and payment chase" }, terminal: true },
});

/** Invoice chase: started the moment an invoice is issued. A customer on the automatic-email list is emailed straight away;
 * for anyone else the one task is the office's approval of that email (approve, edit the message first, or reject to close it).
 * It then follows the collections routine: friendly reminder on day 1 overdue, a call on day 7, a formal notice on day 14,
 * the owner on day 30. Every step first checks whether the invoice has been paid and stops if so.
 * Card links expire (24 hours at most), so a fresh one is made just before each email that carries it. */
export const invoiceChase = defineWorkflow(
  { id: INVOICE_CHASE_ID, name: "Invoice and payment chase" },
  [
    { id: "trigger", type: "TRIGGER", stepKey: "manual", label: "An invoice was issued", config: { fields: [{ name: "invoiceId", description: "The invoice's id", example: "", required: true }] } },
    { id: "create_link", type: "ACTION", stepKey: "createPaymentLink", label: "Create a card payment link", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "load_invoice", type: "ACTION", stepKey: "getInvoice", label: "Read the invoice", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "decision_email", type: "DECISION", label: "Do we have their email?" },
    {
      id: "send_invoice",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Email the invoice (PDF attached) with how to pay",
      config: { template: "invoice_send", params: { to: ref("load_invoice.clientEmail"), variables: { clientFirstName: ref("load_invoice.clientFirstName"), title: ref("load_invoice.jobTitle"), number: ref("load_invoice.number"), balanceText: ref("load_invoice.balanceText"), dueNote: ref("load_invoice.dueNote"), payBlock: ref("load_invoice.payBlock") }, variableDefaults: { message: ref("load_invoice.introText") }, attachInvoiceId: ref("trigger.invoiceId") } },
      retryPolicy: GMAIL_RETRY,
      onFailureNodeId: "send_by_hand",
    },
    {
      id: "approve_send",
      type: "HUMAN_TASK",
      label: "Office approves sending the invoice",
      config: { taskType: "approve_invoice_email", assigneeRole: "EDITOR", approval: true, reviewsNodeId: "send_invoice_approved", editsVariable: "message", editHint: "The invoice amount, how to pay and the sign-off are added automatically below your message, and the invoice PDF is attached.", description: "The invoice has been issued. Read the email below. Edit the message if you want to change it, then approve to send it now (with the PDF and payment link), or reject to close this task without emailing the customer." },
    },
    { id: "decision_send_approved", type: "DECISION", label: "Approved?" },
    {
      id: "send_invoice_approved",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Email the approved invoice (PDF attached)",
      config: { template: "invoice_send", params: { to: ref("load_invoice.emailAddress"), variables: { clientFirstName: ref("load_invoice.clientFirstName"), title: ref("load_invoice.jobTitle"), number: ref("load_invoice.number"), balanceText: ref("load_invoice.balanceText"), dueNote: ref("load_invoice.dueNote"), payBlock: ref("load_invoice.payBlock"), message: ref("approve_send.message") }, variableDefaults: { message: ref("load_invoice.introText") }, attachInvoiceId: ref("trigger.invoiceId") } },
      retryPolicy: GMAIL_RETRY,
      onFailureNodeId: "send_by_hand",
    },
    {
      id: "send_by_hand",
      type: "HUMAN_TASK",
      label: "Send the invoice by hand",
      config: { taskType: "send_invoice_by_hand", assigneeRole: "EDITOR", reviewsNodeId: "send_invoice_approved", description: "The invoice was not emailed: either the customer has no email address on file, or sending failed (the run's history shows which). The email is shown below - send it to the customer yourself, then mark this done.", terminal: true },
    },
    { id: "note_issued", type: "ACTION", stepKey: "addTimelineNote", label: "Note it on the client's history", config: { params: { clientId: ref("load_invoice.clientId"), summary: "Invoice emailed with a payment link", workflow: "Invoice and payment chase" } } },
    { id: "wait_due", type: "DELAY", label: "Wait until one day past the due date", config: { seconds: 8 * DAYS } },
    { id: "refresh_1", type: "ACTION", stepKey: "createPaymentLink", label: "Refresh the pay link (links expire)", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "check_1", type: "ACTION", stepKey: "getInvoice", label: "Paid yet?", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "decision_1", type: "DECISION", label: "Still unpaid?" },
    { id: "decision_remind_email", type: "DECISION", label: "May we send the reminder automatically?" },
    {
      id: "approve_reminder",
      type: "HUMAN_TASK",
      label: "Office approves the reminder",
      config: { taskType: "approve_invoice_reminder", assigneeRole: "EDITOR", approval: true, reviewsNodeId: "reminder_approved", description: "The invoice is overdue. Read the reminder below. Approve to send it, or reject to skip it." },
    },
    { id: "decision_reminder_approved", type: "DECISION", label: "Approved?" },
    {
      id: "reminder_approved",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Send the approved reminder",
      config: { template: "invoice_reminder", params: { to: ref("check_1.emailAddress"), variables: { clientFirstName: ref("check_1.clientFirstName"), number: ref("check_1.number"), balanceText: ref("check_1.balanceText"), dueDate: ref("check_1.dueDate"), payBlock: ref("check_1.payBlock") } } },
      retryPolicy: GMAIL_RETRY,
    },
    {
      id: "reminder",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Day 1: friendly reminder",
      config: { template: "invoice_reminder", params: { to: ref("check_1.clientEmail"), variables: { clientFirstName: ref("check_1.clientFirstName"), number: ref("check_1.number"), balanceText: ref("check_1.balanceText"), dueDate: ref("check_1.dueDate"), payBlock: ref("check_1.payBlock") } } },
      retryPolicy: GMAIL_RETRY,
    },
    { id: "wait_2", type: "DELAY", label: "Wait until day 7", config: { seconds: 6 * DAYS } },
    { id: "check_2", type: "ACTION", stepKey: "getInvoice", label: "Paid yet?", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "decision_2", type: "DECISION", label: "Still unpaid?" },
    {
      id: "call_task",
      type: "HUMAN_TASK",
      label: "Day 7: office phones the customer",
      config: { taskType: "call_about_overdue_invoice", assigneeRole: "EDITOR", description: "The invoice is a week overdue and has had a reminder. Phone the customer, find out when they will pay, note it on the invoice, then mark this done." },
    },
    { id: "wait_3", type: "DELAY", label: "Wait until day 14", config: { seconds: 7 * DAYS } },
    { id: "refresh_3", type: "ACTION", stepKey: "createPaymentLink", label: "Refresh the pay link (links expire)", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "check_3", type: "ACTION", stepKey: "getInvoice", label: "Paid yet?", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "decision_3", type: "DECISION", label: "Still unpaid?" },
    { id: "decision_notice_email", type: "DECISION", label: "May we send the notice automatically?" },
    {
      id: "approve_notice",
      type: "HUMAN_TASK",
      label: "Office approves the formal notice",
      config: { taskType: "approve_invoice_notice", assigneeRole: "EDITOR", approval: true, reviewsNodeId: "notice_approved", description: "The invoice is two weeks overdue. Read the formal notice below. Approve to send it, or reject to skip it." },
    },
    { id: "decision_notice_approved", type: "DECISION", label: "Approved?" },
    {
      id: "notice_approved",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Send the approved formal notice",
      config: { template: "invoice_notice", params: { to: ref("check_3.emailAddress"), variables: { clientName: ref("check_3.clientName"), title: ref("check_3.jobTitle"), number: ref("check_3.number"), daysOverdue: ref("check_3.daysOverdue"), balanceText: ref("check_3.balanceText"), payBlock: ref("check_3.payBlock") } } },
      retryPolicy: GMAIL_RETRY,
    },
    {
      id: "notice",
      type: "ACTION",
      stepKey: "sendTemplatedEmail",
      label: "Day 14: formal payment notice",
      config: { template: "invoice_notice", params: { to: ref("check_3.clientEmail"), variables: { clientName: ref("check_3.clientName"), title: ref("check_3.jobTitle"), number: ref("check_3.number"), daysOverdue: ref("check_3.daysOverdue"), balanceText: ref("check_3.balanceText"), payBlock: ref("check_3.payBlock") } } },
      retryPolicy: GMAIL_RETRY,
    },
    { id: "wait_4", type: "DELAY", label: "Wait until day 30", config: { seconds: 16 * DAYS } },
    { id: "check_4", type: "ACTION", stepKey: "getInvoice", label: "Paid yet?", config: { params: { invoiceId: ref("trigger.invoiceId") } } },
    { id: "decision_4", type: "DECISION", label: "Still unpaid?" },
    {
      id: "owner_escalation",
      type: "HUMAN_TASK",
      label: "Day 30: owner decides what next",
      config: { taskType: "escalate_overdue_invoice", assigneeRole: "ADMIN", description: "This invoice is 30 days overdue after a reminder, a call and a formal notice. Decide: payment plan, final demand, or write it off. Record the decision on the invoice, then mark this done.", terminal: true },
    },
    note("note_rejected", "Invoice not emailed - the office rejected the email", "Rejected - nothing emailed"),
    note("note_paid_1", "Invoice paid - chasing stopped"),
    note("note_paid_2", "Invoice paid after the reminder - chasing stopped"),
    note("note_paid_3", "Invoice paid after the call - chasing stopped"),
    note("note_paid_4", "Invoice paid after the formal notice - chasing stopped"),
  ],
  [
    { from: "trigger", to: "create_link" },
    { from: "create_link", to: "load_invoice" },
    { from: "load_invoice", to: "decision_email" },
    { from: "decision_email", to: "send_invoice", when: { field: "load_invoice.hasEmail", op: "eq", value: true }, label: "Has email" },
    { from: "decision_email", to: "approve_send", when: { field: "load_invoice.hasEmailAddress", op: "eq", value: true }, label: "Needs approval" },
    { from: "decision_email", to: "send_by_hand", label: "No email address" },
    { from: "approve_send", to: "decision_send_approved" },
    { from: "decision_send_approved", to: "send_invoice_approved", when: { field: "approve_send.approved", op: "eq", value: true }, label: "Approved" },
    { from: "decision_send_approved", to: "note_rejected", label: "Rejected" },
    { from: "send_invoice_approved", to: "note_issued" },
    { from: "send_invoice", to: "note_issued" },
    { from: "note_issued", to: "wait_due" },
    { from: "wait_due", to: "refresh_1" },
    { from: "refresh_1", to: "check_1" },
    { from: "check_1", to: "decision_1" },
    { from: "decision_1", to: "decision_remind_email", when: { field: "check_1.isOpen", op: "eq", value: true }, label: "Unpaid" },
    { from: "decision_1", to: "note_paid_1", label: "Paid" },
    { from: "decision_remind_email", to: "reminder", when: { field: "check_1.hasEmail", op: "eq", value: true }, label: "Automatic" },
    { from: "decision_remind_email", to: "approve_reminder", when: { field: "check_1.hasEmailAddress", op: "eq", value: true }, label: "Needs approval" },
    { from: "decision_remind_email", to: "wait_2", label: "No email address - skip" },
    { from: "approve_reminder", to: "decision_reminder_approved" },
    { from: "decision_reminder_approved", to: "reminder_approved", when: { field: "approve_reminder.approved", op: "eq", value: true }, label: "Approved" },
    { from: "decision_reminder_approved", to: "wait_2", label: "Rejected - skip the reminder" },
    { from: "reminder_approved", to: "wait_2" },
    { from: "reminder", to: "wait_2" },
    { from: "wait_2", to: "check_2" },
    { from: "check_2", to: "decision_2" },
    { from: "decision_2", to: "call_task", when: { field: "check_2.isOpen", op: "eq", value: true }, label: "Unpaid" },
    { from: "decision_2", to: "note_paid_2", label: "Paid" },
    { from: "call_task", to: "wait_3" },
    { from: "wait_3", to: "refresh_3" },
    { from: "refresh_3", to: "check_3" },
    { from: "check_3", to: "decision_3" },
    { from: "decision_3", to: "decision_notice_email", when: { field: "check_3.isOpen", op: "eq", value: true }, label: "Unpaid" },
    { from: "decision_3", to: "note_paid_3", label: "Paid" },
    { from: "decision_notice_email", to: "notice", when: { field: "check_3.hasEmail", op: "eq", value: true }, label: "Automatic" },
    { from: "decision_notice_email", to: "approve_notice", when: { field: "check_3.hasEmailAddress", op: "eq", value: true }, label: "Needs approval" },
    { from: "decision_notice_email", to: "wait_4", label: "No email address - skip" },
    { from: "approve_notice", to: "decision_notice_approved" },
    { from: "decision_notice_approved", to: "notice_approved", when: { field: "approve_notice.approved", op: "eq", value: true }, label: "Approved" },
    { from: "decision_notice_approved", to: "wait_4", label: "Rejected - skip the notice" },
    { from: "notice_approved", to: "wait_4" },
    { from: "notice", to: "wait_4" },
    { from: "wait_4", to: "check_4" },
    { from: "check_4", to: "decision_4" },
    { from: "decision_4", to: "owner_escalation", when: { field: "check_4.isOpen", op: "eq", value: true }, label: "Unpaid" },
    { from: "decision_4", to: "note_paid_4", label: "Paid" },
  ],
);
